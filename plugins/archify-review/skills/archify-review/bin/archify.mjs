function commandValidate(args) {
  const qualityArgs = extractQualityArgs(args);
  args = qualityArgs.rest;
  const quality = qualityArgs.quality;
  const knownOptions = new Set(['--json']);
  const unknown = args.filter((arg) => arg.startsWith('--') && !knownOptions.has(arg));
  if (unknown.length) rejectCliArgument(`Unknown validate option "${unknown[0]}".`, {
    code: 'cli/unknown-option',
    subject: { option: unknown[0] },
    supportedFixes: ['remove the unknown option and retry'],
  });
  const json = args.includes('--json');
  const rest = args.filter((arg) => !knownOptions.has(arg));
  const [type, input] = rest;
  if (!type || !input || rest.length !== 2) rejectCliArgument(usage(), {
    code: 'cli/usage',
    supportedFixes: ['use: archify validate <type> <input.json> [options]'],
  });
  const renderer = rendererPath(type);

  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'archify-validate-'));
  const out = path.join(tmp, `${type}.html`);
  let exitCode = 0;

  try {
    const render = runNode([renderer, input, out], {
      stdio: 'pipe',
      env: rendererEnv(quality, true),
    });
    if (render.status !== 0) {
      const failure = rendererFailure(render);
      reportValidateFailure({
        json,
        stage: failure.diagnostics.some((entry) => entry.code.startsWith('input/')) ? 'input' : 'render',
        type,
        input: path.resolve(input),
        error: failure.error,
        diagnostics: failure.diagnostics,
        status: render.status ?? 1,
      });
      exitCode = render.status ?? 1;
    } else {
      const check = runNode([path.join(skillRoot, 'scripts/check-render-output.mjs'), out], { stdio: 'pipe' });
      if (check.status !== 0) {
        let checker;
        try {
          checker = JSON.parse(check.stdout);
          checker.file = path.resolve(input);
        } catch {
          checker = { ok: false, diagnostic: 'Artifact checker failed without a parseable receipt.' };
        }
        reportValidateFailure({
          json,
          stage: 'check',
          type,
          input: path.resolve(input),
          error: 'Final artifact check failed.',
          diagnostics: checkerDiagnostics(checker),
          checker,
          status: check.status ?? 1,
        });
        exitCode = check.status ?? 1;
      } else {
        const result = JSON.parse(check.stdout);
        if (json) {
          console.log(JSON.stringify({
            schemaVersion: 1,
            ok: true,
            command: 'validate',
            type,
            input: path.resolve(input),
            checks: result.checks,
            composition: result.composition,
          }, null, 2));
        } else {
          console.log(`ok ${type} ${path.resolve(input)} (${result.checks.length} artifact checks; composition ${result.composition.profile}: ${result.composition.summary.errors} errors, ${result.composition.summary.warnings} warnings)`);
        }
      }
    }
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }

  if (exitCode !== 0) process.exitCode = exitCode;
}

async function commandReviewCheck(argv) {
  const { checkSpec, loadHunks, summarize } = await import('../renderers/shared/review-check.mjs');
  const repoAt = argv.indexOf('--repo');
  const specPath = argv.find((a, i) => !a.startsWith('--') && i !== repoAt + 1);
  if (!specPath || repoAt < 0 || !argv[repoAt + 1]) fail('Usage: archify review-check <spec.json> --repo <git repo> [--json]');
  const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));
  if (!spec.changes?.slice && !spec.changes?.commits?.length) fail('spec has no changes.commits[].sha or changes.slice to check against.');
  const repo = path.resolve(argv[repoAt + 1]);
  let hunks;
  try { hunks = loadHunks(repo, spec.changes); } catch (error) { fail(error.message, 1); }
  const findings = checkSpec(spec, hunks);
  const summary = summarize(findings);
  if (argv.includes('--json')) console.log(JSON.stringify({ summary, findings }, null, 2));
  else {
    for (const f of findings) console.log(`${f.severity} ${f.rule} ${f.subject}: ${f.detail}\n  fix: ${f.fix}`);
    console.log(`review-check: ${summary.errors} errors, ${summary.warnings} warnings`);
  }
  if (summary.errors) process.exitCode = 1;
}

const [command, ...args] = process.argv.slice(2);

try {
  switch (command) {
    case undefined:
    case '-h':
    case '--help':
    case 'help':
      console.log(usage());
      break;
    case 'render':
      commandRender(args);
      break;
    case 'deliver':
      await commandDeliver(args);
      break;
    case 'validate':
      commandValidate(args);
      break;
    case 'review-check':
      await commandReviewCheck(args);
      break;
    case 'visual-check':
      await commandVisualCheck(args);
      break;
    case 'doctor':
      await commandDoctor();
      break;
    case 'demo':
      commandDemo(args);
      break;
    default:
      fail(`Unknown command "${command}".\n\n${usage()}`);
  }
} catch (error) {
  if (!error.archifyArgument) throw error;
  if (['validate', 'deliver'].includes(command) && args.includes('--json')) {
    reportArtifactArgumentFailure(command, error);
  } else {
    fail(error.message);
  }
}
